DROP SCHEMA IF EXISTS s1_library CASCADE;
CREATE SCHEMA s1_library;
SET search_path TO s1_library, public;

-- Step 1
CREATE TABLE s1_library.books (
    book_id integer PRIMARY KEY,
    title text NOT NULL,
    available_copies integer NOT NULL CHECK (available_copies >= 0)
);

CREATE TABLE s1_library.book_loans (
    loan_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id integer NOT NULL REFERENCES s1_library.books(book_id),
    student_number text NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    status text NOT NULL CHECK (status IN ('ACTIVE','RETURNED'))
);

