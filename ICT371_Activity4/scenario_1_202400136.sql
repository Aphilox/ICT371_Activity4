-- Step 6
CREATE OR REPLACE PROCEDURE s1_library.return_book(p_loan_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_book_id integer;
    v_quantity integer;
BEGIN
    SELECT book_id, quantity INTO v_book_id, v_quantity
    FROM s1_library.book_loans
    WHERE loan_id = p_loan_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active loan with ID %', p_loan_id;
        RETURN;
    END IF;

    UPDATE s1_library.book_loans
    SET status = 'RETURNED'
    WHERE loan_id = p_loan_id;

    UPDATE s1_library.books
    SET available_copies = available_copies + v_quantity
    WHERE book_id = v_book_id;

    RAISE NOTICE 'Loan % returned; % copies restored', p_loan_id, v_quantity;
END; $$;

