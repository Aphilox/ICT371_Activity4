-- Step 7
CREATE OR REPLACE PROCEDURE s1_library.show_low_stock()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT title, available_copies
        FROM s1_library.books
        WHERE available_copies <= 2
        ORDER BY book_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low stock: % (% remaining)', v_item.title, v_item.available_copies;
    END LOOP;
    CLOSE c_low;
END; $$;

CALL s1_library.show_low_stock();

