-- Step 1
CREATE TABLE s2_lab.lab_sessions (
    session_id integer PRIMARY KEY,
    session_name text NOT NULL,
    available_workstations integer NOT NULL CHECK (available_workstations >= 0)
);

CREATE TABLE s2_lab.reservations (
    reservation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id integer NOT NULL REFERENCES s2_lab.lab_sessions(session_id),
    lecturer text NOT NULL,
    workstations integer NOT NULL CHECK (workstations > 0),
    status text NOT NULL CHECK (status IN ('ACTIVE','CANCELLED'))
);

